// T009 (FR-425, FR-430, FR-431, FR-436; research R-302, R-304; contracts/video.md, "The LiveKit
// adapter"): LiveKit behind the video port, with no network (ARCHITECTURE §13, "Ports"). Every
// request the SDK would send is answered by a recording `fetch` that knows only the two calls the
// adapter makes and refuses anything else, so no request can leave the machine. Every webhook is a
// payload of the shape LiveKit sends (`livekit.WebhookEvent` in protobuf JSON, as
// `@livekit/protocol` 1.51.0 reads it and LiveKit's webhook documentation shows it), signed here as
// LiveKit signs it: a JWT under the project's key and secret whose `sha256` claim is the body's
// digest. The key and the secret are generated by this spec at each run; none is written in it, and
// no real one is read (R-SEC-1).
import { createHash, randomBytes } from 'node:crypto';
import { addHours, unixSeconds } from '@ijazah/time';
import { AccessToken, TokenVerifier, WebhookReceiver } from 'livekit-server-sdk';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { EventSignatureError, MalformedEventError } from '../inbound-event.js';
import { LiveKitVideoAdapter } from './livekit.adapter.js';

const API_KEY = `APIspec${randomBytes(6).toString('hex')}`;
const API_SECRET = randomBytes(32).toString('base64url');
const MEDIA_KEY_SECRET = randomBytes(32);
// A reserved name (RFC 6761): never resolved, and not LiveKit Cloud's, so the SDK tries no failover.
const LIVEKIT_URL = 'wss://video.ijazah.invalid';

const SESSION = '01928c3e-7a10-7000-8000-000000000001';
const STUDENT = '01928c3e-7a10-7000-8000-0000000000a1';
const TIMEOUTS = { emptyTimeoutSeconds: 300, departureTimeoutSeconds: 20 } as const;

const NOW = new Date('2026-11-08T17:00:00.400Z');
const SCHEDULED_END = new Date('2026-11-08T17:45:00.900Z');
/** 2026-11-08T17:00:05Z and 17:44:58Z in UNIX seconds, as LiveKit writes `createdAt`. */
const JOINED_AT = '1794157205';
const ENDED_AT = '1794159898';

interface Recorded {
  readonly url: string;
  readonly authorization: string | null;
  readonly body: unknown;
}

const requests: Recorded[] = [];
/** What the next RoomService call answers, by method; anything not named here is refused. */
let answers: Record<string, () => Response> = {};

function json(status: number, body: unknown): Response {
  return new Response(JSON.stringify(body), {
    status,
    headers: { 'content-type': 'application/json' },
  });
}

beforeEach(() => {
  requests.length = 0;
  answers = {};
  vi.useFakeTimers({ toFake: ['Date'] });
  vi.setSystemTime(NOW);
  vi.stubGlobal('fetch', (input: string | URL | Request, init?: RequestInit) => {
    const url = String(input);
    const headers = new Headers(init?.headers);
    requests.push({
      url,
      authorization: headers.get('authorization'),
      body: typeof init?.body === 'string' ? (JSON.parse(init.body) as unknown) : undefined,
    });
    const method = /^https:\/\/video\.ijazah\.invalid\/twirp\/livekit\.RoomService\/(\w+)$/.exec(
      url,
    )?.[1];
    const answer = method === undefined ? undefined : answers[method];
    if (answer === undefined) return Promise.reject(new Error(`no recorded answer for ${url}`));
    return Promise.resolve(answer());
  });
});

afterEach(() => {
  vi.unstubAllGlobals();
  vi.useRealTimers();
  vi.restoreAllMocks();
});

function adapter(): LiveKitVideoAdapter {
  return new LiveKitVideoAdapter({
    url: LIVEKIT_URL,
    apiKey: API_KEY,
    apiSecret: API_SECRET,
    // T084: generated at each run, as the keys are (R-SEC-1).
    mediaKeySecret: MEDIA_KEY_SECRET,
  });
}

/** The room LiveKit answers `CreateRoom` with (protobuf JSON, as its server sends it). */
const RECORDED_ROOM = {
  sid: 'RM_hycBMAjmt6Ub',
  name: SESSION,
  emptyTimeout: 300,
  departureTimeout: 20,
  maxParticipants: 2,
  creationTime: '1794157200',
  creationTimeMs: '1794157200123',
  enabledCodecs: [{ mime: 'audio/opus' }, { mime: 'video/VP8' }, { mime: 'video/H264' }],
};

/** A participant as LiveKit reports it in `participant_*` events. */
const RECORDED_PARTICIPANT = {
  sid: 'PA_Lv3J9hDjGWkE',
  identity: STUDENT,
  state: 'ACTIVE',
  joinedAt: JOINED_AT,
  joinedAtMs: '1794157205412',
  version: 2,
  permission: { canSubscribe: true, canPublish: true, hidden: false },
  region: 'germany2',
  isPublisher: true,
};

function recordedEvent(event: string, fields: Record<string, unknown> = {}): string {
  return JSON.stringify({
    event,
    room: { ...RECORDED_ROOM, numParticipants: 1 },
    ...(event.startsWith('participant_') || event.startsWith('track_')
      ? { participant: RECORDED_PARTICIPANT }
      : {}),
    id: 'EV_eugWmGhovZmm',
    createdAt: JOINED_AT,
    ...fields,
  });
}

/** Signed as LiveKit signs a webhook: a JWT under the key and secret carrying the body's digest. */
async function signed(
  body: string,
  key = API_KEY,
  secret = API_SECRET,
): Promise<Record<string, string>> {
  const token = new AccessToken(key, secret);
  token.sha256 = createHash('sha256').update(body).digest('base64');
  return { authorization: await token.toJwt() };
}

describe('the LiveKit adapter: rooms (T009, R-302, FR-436)', () => {
  it('creates the room named for the session, for two, with the two timeouts as given', async () => {
    answers['CreateRoom'] = () => json(200, RECORDED_ROOM);

    expect(await adapter().createRoom(SESSION, TIMEOUTS)).toBe(SESSION);
    expect(requests).toHaveLength(1);
    expect(requests[0]?.url).toBe(
      'https://video.ijazah.invalid/twirp/livekit.RoomService/CreateRoom',
    );
    expect(requests[0]?.body).toEqual({
      name: SESSION,
      emptyTimeout: 300,
      departureTimeout: 20,
      maxParticipants: 2,
    });
    expect(requests[0]?.authorization).toMatch(/^Bearer /);
  });

  it('answers the existing room when asked again, as LiveKit answers it, so a retried join opens one', async () => {
    answers['CreateRoom'] = () => json(200, { ...RECORDED_ROOM, numParticipants: 1 });
    const video = adapter();

    expect(await video.createRoom(SESSION, TIMEOUTS)).toBe(SESSION);
    expect(await video.createRoom(SESSION, TIMEOUTS)).toBe(SESSION);
  });

  it('passes on a refusal by LiveKit', async () => {
    answers['CreateRoom'] = () => json(401, { code: 'unauthenticated', msg: 'invalid token' });

    await expect(adapter().createRoom(SESSION, TIMEOUTS)).rejects.toThrow();
  });

  it('ends the room by deleting it, and an ended or absent room is not an error (FR-482)', async () => {
    answers['DeleteRoom'] = () => json(200, {});
    await expect(adapter().endRoom(SESSION)).resolves.toBeUndefined();
    expect(requests[0]?.url).toBe(
      'https://video.ijazah.invalid/twirp/livekit.RoomService/DeleteRoom',
    );
    expect(requests[0]?.body).toEqual({ room: SESSION });

    answers['DeleteRoom'] = () =>
      json(404, { code: 'not_found', msg: 'requested room does not exist' });
    await expect(adapter().endRoom(SESSION)).resolves.toBeUndefined();
  });

  it('passes on any other failure to end the room', async () => {
    answers['DeleteRoom'] = () => json(401, { code: 'unauthenticated', msg: 'invalid token' });

    await expect(adapter().endRoom(SESSION)).rejects.toThrow();
  });
});

describe('the LiveKit adapter: tokens (T009, R-302, FR-430, FR-431)', () => {
  async function claimsOf(credential: string): Promise<Record<string, unknown>> {
    return (await new TokenVerifier(API_KEY, API_SECRET).verify(credential)) as Record<
      string,
      unknown
    >;
  }

  it("mints the participant's token: their id, the room, publish and subscribe, nothing more", async () => {
    const token = await adapter().createSessionToken(SESSION, STUDENT, {
      validUntil: SCHEDULED_END,
    });

    // The project's address, the phone's to connect to (the note under T011, K1).
    expect(token).toMatchObject({
      sessionId: SESSION,
      participantUserId: STUDENT,
      serverUrl: LIVEKIT_URL,
    });
    const claims = await claimsOf(token.credential);
    expect(claims['sub']).toBe(STUDENT);
    expect(claims['iss']).toBe(API_KEY);
    expect(claims['video']).toEqual({
      roomJoin: true,
      room: SESSION,
      canPublish: true,
      canSubscribe: true,
      canPublishData: false,
    });
    expect(claims).not.toHaveProperty('name');
    expect(claims).not.toHaveProperty('metadata');
    expect(requests).toEqual([]);
  });

  it('ends its life by validUntil, never after: a second before its whole second', async () => {
    const lastSecond = unixSeconds(new Date('2026-11-08T17:44:59Z'));
    const fractional = await adapter().createSessionToken(SESSION, STUDENT, {
      validUntil: SCHEDULED_END,
    });
    // One second kept for the SDK's own reading of the clock, so it can never outlive the end.
    expect((await claimsOf(fractional.credential))['exp']).toBe(lastSecond);

    vi.setSystemTime(new Date('2026-11-08T17:00:00.000Z'));
    const whole = await adapter().createSessionToken(SESSION, STUDENT, {
      validUntil: new Date('2026-11-08T17:45:00.000Z'),
    });
    expect((await claimsOf(whole.credential))['exp']).toBe(lastSecond);
  });

  it('refuses a validUntil with no whole second left, rather than the SDK’s six-hour default', async () => {
    for (const validUntil of [
      new Date('2026-11-08T17:00:01.000Z'),
      new Date('2026-11-08T16:00:00Z'),
    ]) {
      await expect(adapter().createSessionToken(SESSION, STUDENT, { validUntil })).rejects.toThrow(
        RangeError,
      );
    }
  });

  it('refuses a token for an empty session or participant (R-GENDER-7)', async () => {
    const validity = { validUntil: SCHEDULED_END };

    await expect(adapter().createSessionToken('', STUDENT, validity)).rejects.toThrow(RangeError);
    await expect(adapter().createSessionToken(SESSION, '', validity)).rejects.toThrow(RangeError);
  });
});

describe('the LiveKit adapter: webhooks (T009, R-303, R-304, R-SESS-7)', () => {
  it.each([
    ['participant_joined', 'joined'],
    ['participant_left', 'left'],
    ['participant_connection_aborted', 'left'],
  ] as const)('maps %s to %s: the identity, the connection, createdAt', async (event, type) => {
    const body = recordedEvent(event);

    expect(
      await adapter().verifyAndParseParticipantEvent(Buffer.from(body), await signed(body)),
    ).toEqual({
      providerEventId: 'EV_eugWmGhovZmm',
      sessionId: SESSION,
      type,
      participantUserId: STUDENT,
      connectionRef: 'PA_Lv3J9hDjGWkE',
      occurredAt: new Date('2026-11-08T17:00:05Z'),
    });
  });

  it('maps room_finished to the room’s end, with no participant and no connection', async () => {
    const body = recordedEvent('room_finished', {
      room: { ...RECORDED_ROOM, numParticipants: 0 },
      createdAt: ENDED_AT,
      roomEndReason: 'DEPARTURE_TIMEOUT',
    });

    expect(
      await adapter().verifyAndParseParticipantEvent(Buffer.from(body), await signed(body)),
    ).toEqual({
      providerEventId: 'EV_eugWmGhovZmm',
      sessionId: SESSION,
      type: 'room_ended',
      occurredAt: new Date('2026-11-08T17:44:58Z'),
    });
  });

  it.each([
    'room_started',
    'track_published',
    'track_unpublished',
    'egress_ended',
    'agent_job_started',
  ])('answers ignored for %s, which is not attendance', async (event) => {
    const body = recordedEvent(event);

    expect(
      await adapter().verifyAndParseParticipantEvent(Buffer.from(body), await signed(body)),
    ).toEqual({ kind: 'ignored' });
  });

  it('verifies through WebhookReceiver.receive with the body and the Authorization header, never skipAuth', async () => {
    const receive = vi.spyOn(WebhookReceiver.prototype, 'receive');
    const body = recordedEvent('participant_joined');
    const headers = await signed(body);

    await adapter().verifyAndParseParticipantEvent(Buffer.from(body), headers);

    expect(receive).toHaveBeenCalledTimes(1);
    expect(receive.mock.calls[0]).toEqual([body, headers['authorization']]);
  });

  it('reads the Authorization header whatever its case', async () => {
    const body = recordedEvent('participant_joined');
    const { authorization } = await signed(body);

    await expect(
      adapter().verifyAndParseParticipantEvent(Buffer.from(body), { Authorization: authorization }),
    ).resolves.toMatchObject({ type: 'joined' });
  });

  it('refuses a wrong secret, another key, no signature and a body changed after signing (SC-406)', async () => {
    const body = recordedEvent('participant_joined');
    const changed = body.replace('EV_eugWmGhovZmm', 'EV_replayedAnew0');
    const video = adapter();

    const forgeries: [string, Record<string, string | undefined>][] = [
      [body, await signed(body, API_KEY, randomBytes(32).toString('base64url'))],
      [body, await signed(body, `APIother${randomBytes(4).toString('hex')}`, API_SECRET)],
      [body, {}],
      [body, { authorization: '' }],
      [body, { authorization: 'not-a-jwt' }],
      [changed, await signed(body)],
    ];
    for (const [rawBody, headers] of forgeries) {
      await expect(
        video.verifyAndParseParticipantEvent(Buffer.from(rawBody), headers),
      ).rejects.toThrow(EventSignatureError);
    }
  });

  it('refuses a signature that has expired', async () => {
    const body = recordedEvent('participant_joined');
    const headers = await signed(body);
    // Past the six hours the signing token was minted for.
    vi.setSystemTime(new Date(addHours(NOW, 7)));

    await expect(
      adapter().verifyAndParseParticipantEvent(Buffer.from(body), headers),
    ).rejects.toThrow(EventSignatureError);
  });

  it.each([
    ['a body that is not JSON', 'not json: student 01000000000'],
    [
      'a field of the wrong type',
      recordedEvent('participant_joined', { createdAt: 'student 01000000000' }),
    ],
    ['an event with no id', recordedEvent('participant_joined', { id: '' })],
    ['an event with no instant', recordedEvent('participant_joined', { createdAt: '0' })],
    ['an event with no room', recordedEvent('participant_joined', { room: undefined })],
    [
      'a join with no identity',
      recordedEvent('participant_joined', {
        participant: { ...RECORDED_PARTICIPANT, identity: '' },
      }),
    ],
    [
      'a leave with no connection',
      recordedEvent('participant_left', { participant: { ...RECORDED_PARTICIPANT, sid: '' } }),
    ],
    ['a leave with no participant', recordedEvent('participant_left', { participant: undefined })],
    ['a room’s end with no room', recordedEvent('room_finished', { room: undefined })],
  ])('rejects a signed body it cannot read, %s, quoting nothing of it', async (_name, body) => {
    const refusal = adapter().verifyAndParseParticipantEvent(Buffer.from(body), await signed(body));

    await expect(refusal).rejects.toThrow(MalformedEventError);
    await expect(refusal).rejects.not.toThrow('01000000000');
  });

  it('makes no request to LiveKit to verify or to mint', async () => {
    const body = recordedEvent('participant_left');
    const video = adapter();

    await video.verifyAndParseParticipantEvent(Buffer.from(body), await signed(body));
    await video.createSessionToken(SESSION, STUDENT, { validUntil: SCHEDULED_END });

    expect(requests).toEqual([]);
  });
});
